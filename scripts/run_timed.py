"""Time to first approval for N assets starting Phase 2 together, BIO vs Wong.

p_priority has no verified value yet (ASSUMPTION_P_PRIORITY), so it must be passed explicitly.
gap_months (ASSUMPTION_GAP_MONTHS) defaults to 0; review_extra_months stays at its default 0.

Outputs:
  data/processed/timed_first_approval.csv
  docs/timed_results.md

Usage: python scripts/run_timed.py --p-priority 0 0.5 1 --gap-months 0 3 6
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from biotech_pipeline_mc.gates import DEFAULT_SEED
from biotech_pipeline_mc.params import DURATIONS_MAIN_CSV, SCENARIOS, load_gate_probs
from biotech_pipeline_mc.timing import load_timing_inputs, simulate_portfolio_timed

ROOT = Path(__file__).resolve().parents[1]
CSV_OUT = ROOT / "data" / "processed" / "timed_first_approval.csv"
MD_OUT = ROOT / "docs" / "timed_results.md"

N_SIMS = 200_000
PORTFOLIO_SIZES = [1, 3, 5, 10]
QUANTILES = [10, 25, 50, 75, 90]
HORIZONS_YEARS = [5, 7, 10]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--p-priority", type=float, nargs="+", required=True)
    ap.add_argument("--gap-months", type=float, nargs="+", default=[0.0])
    ap.add_argument("--n-sims", type=int, default=N_SIMS)
    args = ap.parse_args()

    timing = load_timing_inputs()
    rows = []
    for gap in args.gap_months:
        for p_priority in args.p_priority:
            for n_assets in PORTFOLIO_SIZES:
                for i, scenario in enumerate(SCENARIOS):
                    gates = load_gate_probs(scenario)
                    # same seed across p_priority / gap cells (common random numbers)
                    rng = np.random.default_rng([DEFAULT_SEED, n_assets, i])
                    res = simulate_portfolio_timed(gates.names, gates.probs, n_assets, args.n_sims,
                                                   timing, p_priority, rng, gap_months=gap)
                    t = res.first_approval_months
                    hit = t[~np.isnan(t)]
                    row = {"gap_months": gap, "p_priority": p_priority, "n_assets": n_assets,
                           "scenario": scenario, "p_zero_approved": round(float(np.isnan(t).mean()), 4)}
                    for q, v in zip(QUANTILES, np.percentile(hit, QUANTILES)):
                        row[f"first_approval_p{q}_months"] = round(float(v), 1)
                    for y in HORIZONS_YEARS:
                        # P(at least one asset approved within y years) = P(first approval <= 12y)
                        row[f"p_approved_within_{y}y"] = round(float((np.nan_to_num(t, nan=np.inf) <= 12 * y).mean()), 4)
                    rows.append(row)

    CSV_OUT.parent.mkdir(parents=True, exist_ok=True)
    with CSV_OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    scen = list(SCENARIOS)

    def cell(gap, p_priority, n_assets):
        return {row["scenario"]: row for row in rows
                if row["gap_months"] == gap and row["p_priority"] == p_priority and row["n_assets"] == n_assets}

    L = [
        "# Time to first approval: BIO vs Wong",
        "",
        "Generated by `scripts/run_timed.py`. Do not edit by hand.",
        "",
        f"- Run at (UTC): {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"- Runs per cell: {args.n_sims:,}; seed {DEFAULT_SEED} (per cell: [seed, N, scenario index], "
        f"shared across p_priority and gap values); numpy {np.__version__}",
        f"- Durations: `{DURATIONS_MAIN_CSV.relative_to(ROOT)}` (rule d) — Phase 2 n={timing.phase2.size:,}, "
        f"Phase 3 n={timing.phase3.size:,}",
        f"- Review: {timing.review_priority:g} months w.p. p_priority, else {timing.review_standard:g} months. "
        "**p_priority has no verified value (ASSUMPTION_P_PRIORITY); sensitivity range shown.**",
        "- gap_months (ASSUMPTION_GAP_MONTHS) is added twice on the path: Phase 2 → Phase 3 and Phase 3 → "
        "submission. **Base case gap = 0, which biases timelines short.** review_extra_months = 0 in all runs.",
        "- All N assets start Phase 2 at month 0 and are independent. No resubmission cycles.",
        "- P(≥1 approved within X y) is unconditional (zero-approval runs count as not approved). "
        "First-approval quantiles are **conditional on at least one approval**.",
        "",
    ]
    for gap in args.gap_months:
        for p_priority in args.p_priority:
            L += [
                f"## gap_months = {gap:g}, p_priority = {p_priority:g}",
                "",
                "| N | " + " | ".join(f"P(≥1 approved within {y}y) {s}" for y in HORIZONS_YEARS for s in scen)
                + " | " + " | ".join(f"P(0 approved) {s}" for s in scen)
                + " | " + " | ".join(f"{s} median (P25–P75), months" for s in scen) + " |",
                "|---|" + "---|" * (len(scen) * (len(HORIZONS_YEARS) + 2)),
            ]
            for n_assets in PORTFOLIO_SIZES:
                r = cell(gap, p_priority, n_assets)
                cells = [f"{r[s][f'p_approved_within_{y}y']:.3f}" for y in HORIZONS_YEARS for s in scen]
                cells += [f"{r[s]['p_zero_approved']:.3f}" for s in scen]
                cells += [f"{r[s]['first_approval_p50_months']} ({r[s]['first_approval_p25_months']}–"
                          f"{r[s]['first_approval_p75_months']})" for s in scen]
                L.append(f"| {n_assets} | " + " | ".join(cells) + " |")
            L.append("")
    L += ["Full quantiles (P10–P90) are in `data/processed/timed_first_approval.csv`.", ""]
    MD_OUT.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
