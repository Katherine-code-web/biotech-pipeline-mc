"""Compare simulated vs analytic gate outcomes for each scenario.

Outputs:
  data/processed/gate_validation.csv
  docs/gate_validation.md

Usage: python scripts/validate_gates.py
"""
from __future__ import annotations

import csv
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from biotech_pipeline_mc.gates import (
    DEFAULT_SEED,
    analytic_at_least_one,
    analytic_stop_distribution,
    simulate_asset,
    simulate_portfolio,
)
from biotech_pipeline_mc.params import SCENARIOS, load_gate_probs

ROOT = Path(__file__).resolve().parents[1]
CSV_OUT = ROOT / "data" / "processed" / "gate_validation.csv"
MD_OUT = ROOT / "docs" / "gate_validation.md"

N_SIMS = 1_000_000
N_PORTFOLIO_SIMS = 200_000
PORTFOLIO_SIZES = [1, 3, 5, 10]
FIELDS = ["scenario", "quantity", "simulated", "analytic", "diff", "se", "z", "n_sims"]


def compare(scenario: str, quantity: str, simulated: float, analytic: float, n: int) -> dict:
    se = float(np.sqrt(analytic * (1 - analytic) / n))
    diff = simulated - analytic
    return {
        "scenario": scenario, "quantity": quantity,
        "simulated": round(simulated, 6), "analytic": round(analytic, 6),
        "diff": round(diff, 6), "se": round(se, 6),
        "z": round(diff / se, 2) if se > 0 else "",
        "n_sims": n,
    }


def main() -> None:
    rows, gate_lines = [], []
    for scenario in SCENARIOS:
        gates = load_gate_probs(scenario)
        gate_lines.append(
            f"- **{scenario}**: " + ", ".join(
                f"{name} = {p:.3f} (`{pid}`)" for name, pid, p in zip(gates.names, gates.param_ids, gates.probs)))

        sim = simulate_asset(gates.probs, N_SIMS, np.random.default_rng(DEFAULT_SEED))
        observed = np.bincount(sim.stopped_at, minlength=len(gates.probs) + 1) / N_SIMS
        expected = analytic_stop_distribution(gates.probs)
        for i, name in enumerate(gates.names):
            rows.append(compare(scenario, f"P(fail at {name})", observed[i], expected[i], N_SIMS))
        rows.append(compare(scenario, "P(approved), 1 asset", observed[-1], expected[-1], N_SIMS))

        for k in PORTFOLIO_SIZES:
            approved = simulate_portfolio(gates.probs, k, N_PORTFOLIO_SIMS, np.random.default_rng(DEFAULT_SEED + k))
            rows.append(compare(scenario, f"P(≥1 approved), N={k}",
                                float((approved > 0).mean()), analytic_at_least_one(gates.probs, k),
                                N_PORTFOLIO_SIMS))

    CSV_OUT.parent.mkdir(parents=True, exist_ok=True)
    with CSV_OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)

    L = [
        "# Gate model: simulated vs analytic",
        "",
        "Generated by `scripts/validate_gates.py`. Do not edit by hand.",
        "",
        f"- Run at (UTC): {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"- Seed: {DEFAULT_SEED} (portfolio runs use seed + N); numpy {np.__version__}",
        f"- Single asset: {N_SIMS:,} runs. Portfolio: {N_PORTFOLIO_SIMS:,} runs per N.",
        "- Gate probabilities (read from `data/assumptions.csv`):",
        *[f"  {g}" for g in gate_lines],
        "",
        "Analytic: P(fail at gate i) = p₁⋯pᵢ₋₁(1 − pᵢ); P(approved) = ∏pᵢ; P(≥1 of N) = 1 − (1 − ∏pᵢ)ᴺ.",
        "SE = √(p(1 − p)/n) using the analytic p; z = diff / SE.",
        "",
        "| Scenario | Quantity | Simulated | Analytic | Diff | SE | z |",
        "|---|---|---|---|---|---|---|",
        *[f"| {r['scenario']} | {r['quantity']} | {r['simulated']:.4f} | {r['analytic']:.4f} | "
          f"{r['diff']:+.4f} | {r['se']:.4f} | {r['z']} |" for r in rows],
        "",
    ]
    MD_OUT.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
